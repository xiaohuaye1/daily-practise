#include <iostream>
using namespace std;
int main(){
    //1整形
    int a=0;
    cin >>a;
    cout<<a<<endl;
    //2浮点型
    float b=0;
    cin >>b;
    cout <<b<<endl;
    //3字符型
    char c='a';
    cin >>c;
    cout<<c<<endl;
    //4字符串
    string str1="hello";
    cin>>str1;
    cout <<str1<<endl;
    //5bool类型
    bool d=false;
    cin>>d;
    cout <<d<<endl;
}